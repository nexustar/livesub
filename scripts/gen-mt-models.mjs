// Regenerate src/mt-models.ts: the models desktop Firefox uses, from Remote
// Settings. (Mozilla's model bucket doesn't always hold the shortlist Firefox
// ships.)
//
// Usage: node scripts/gen-mt-models.mjs

import { writeFileSync } from "node:fs";
import { join } from "node:path";

const RS = "https://firefox.settings.services.mozilla.com/v1/buckets/main/collections/translations-models-v2/records";
const CDN = "https://firefox-settings-attachments.cdn.mozilla.net";
const OUT = join(import.meta.dirname, "..", "src", "mt-models.ts");
// Not Android- or Nightly-only.
const DESKTOP = new Set(["", "env.appinfo.OS != 'Android'"]);
// Firefox's LANGUAGE_MODEL_MAJOR_VERSION.
const MAJOR = 3;

async function json(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  return res.json();
}

const records = (await json(RS)).data;

const ver = (v) => v.split(".").map(Number);
const newer = (a, b) => {
  const [x, y] = [ver(a), ver(b)];
  for (let i = 0; i < Math.max(x.length, y.length); i++) if ((x[i] ?? 0) !== (y[i] ?? 0)) return (x[i] ?? 0) > (y[i] ?? 0);
  return false;
};

const best = new Map();
for (const r of records) {
  if (!DESKTOP.has(r.filter_expression ?? "") || ver(r.version)[0] !== MAJOR) continue;
  const key = `${r.sourceLanguage}|${r.targetLanguage}|${r.fileType}`;
  const cur = best.get(key);
  if (!cur || newer(r.version, cur.version)) best.set(key, r);
}

const pairs = [...new Set([...best.keys()].map((k) => k.split("|").slice(0, 2).join("|")))].sort();
const models = [];
const skipped = [];
for (const pair of pairs) {
  const [from, to] = pair.split("|");
  const rec = (t) => best.get(`${pair}|${t}`);
  const types = rec("vocab") ? ["model", "lex", "vocab"] : ["model", "lex", "srcvocab", "trgvocab"];
  if (!types.every(rec)) {
    skipped.push(`${from}-${to}`);
    continue;
  }
  const files = types.map((t) => {
    const r = rec(t);
    return { name: r.name, record: r.id, path: r.attachment.location, size: r.decompressedSize, sha256: r.decompressedHash };
  });
  const model = rec("model");
  models.push({ from, to, version: model.version, arch: model.architecture, files });
}

// Hashes are checked at download time.
const urls = models.flatMap((m) => m.files.map((f) => `${CDN}/${f.path}`));
for (let i = 0; i < urls.length; i += 16) {
  await Promise.all(urls.slice(i, i + 16).map(async (u) => {
    const res = await fetch(u, { method: "HEAD" });
    if (!res.ok) throw new Error(`HTTP ${res.status} for ${u}`);
  }));
}

const lines = [
  "// GENERATED by scripts/gen-mt-models.mjs, do not edit. Firefox's translation",
  "// models (MPL-2.0); size and sha256 are of the decompressed file.",
  "",
  "export interface MtModelFile {",
  "  name: string;",
  "  record: string;",
  "  path: string;",
  "  size: number;",
  "  sha256: string;",
  "}",
  "export interface MtModel {",
  "  from: string;",
  "  to: string;",
  "  version: string;",
  "  arch: string;",
  "  files: MtModelFile[];",
  "}",
  "",
  `export const MT_BASE_URL = ${JSON.stringify(CDN)};`,
  `export const MT_RECORDS_URL = ${JSON.stringify(RS)};`,
  "",
  "export const MT_MODELS: MtModel[] = [",
  ...models.map((m) => `  ${JSON.stringify(m)},`),
  "];",
  "",
];
writeFileSync(OUT, lines.join("\n"));
console.log(`src/mt-models.ts: ${models.length} directions; incomplete, skipped: ${skipped.join(", ") || "none"}`);
